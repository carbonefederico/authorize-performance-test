#!/usr/bin/env bash
# create-secrets.sh — idempotent cluster Secrets for the campaign.
#   paz-devops-secret   Ping DevOps eval credentials (chart license gate)
#   paz-secrets         sideband shared secret (generated + written back to
#                       .env when empty, so k6 and PAZ share one value across
#                       redeploys) + PAP admin password
#   paz-loadtest        every env key the k6 script reads (overridden per
#                       profile by run-in-cluster.sh --set-string)
set -euo pipefail
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/common.sh"

require_command kubectl
require_command openssl
for name in PING_IDENTITY_DEVOPS_USER PING_IDENTITY_DEVOPS_KEY PAP_ADMIN_PASSWORD \
            SUBJECT_SIGNING_KEY_FILE MCP_AUD PAZ_SIDEBAND_URL SUBJECT_ISSUER; do
  require_value "${name}"
done
[[ -f "${SUBJECT_SIGNING_KEY_FILE}" ]] || {
  echo "Signing key not found: ${SUBJECT_SIGNING_KEY_FILE} (run ./scripts/generate-signing-key.sh)" >&2
  exit 1
}

kubectl -n "${NAMESPACE}" create secret generic paz-devops-secret \
  --from-literal=username="${PING_IDENTITY_DEVOPS_USER}" \
  --from-literal=password="${PING_IDENTITY_DEVOPS_KEY}" \
  --dry-run=client -o yaml | kubectl apply -f -

# Generate the sideband shared secret once and persist it to .env so every
# later script (and redeploy) uses the same value.
if [[ -z "${SIDEBAND_SHARED_SECRET:-}" ]]; then
  SIDEBAND_SHARED_SECRET="$(openssl rand -hex 32)"
  if [[ -f "${ROOT_DIR}/.env" ]]; then
    printf '\n# Generated by create-secrets.sh — shared PDG-TOKEN value\nSIDEBAND_SHARED_SECRET=%s\n' "${SIDEBAND_SHARED_SECRET}" >> "${ROOT_DIR}/.env"
  else
    printf '# Generated by create-secrets.sh — shared PDG-TOKEN value\nSIDEBAND_SHARED_SECRET=%s\n' "${SIDEBAND_SHARED_SECRET}" > "${ROOT_DIR}/.env"
  fi
  export SIDEBAND_SHARED_SECRET
  echo "Generated SIDEBAND_SHARED_SECRET and appended it to .env"
fi

kubectl -n "${NAMESPACE}" create secret generic paz-secrets \
  --from-literal=sideband-shared-secret="${SIDEBAND_SHARED_SECRET}" \
  --from-literal=pap-admin-password="${PAP_ADMIN_PASSWORD}" \
  --dry-run=client -o yaml | kubectl apply -f -

kubectl -n "${NAMESPACE}" create secret generic paz-loadtest \
  --from-literal=PAZ_SIDEBAND_URL="${PAZ_SIDEBAND_URL}" \
  --from-literal=SIDEBAND_SHARED_SECRET="${SIDEBAND_SHARED_SECRET}" \
  --from-literal=MCP_AUD="${MCP_AUD}" \
  --from-literal=SUBJECT_ISSUER="${SUBJECT_ISSUER}" \
  --from-literal=SUBJECT_USER_COUNT="${SUBJECT_USER_COUNT:-100}" \
  --from-file=SUBJECT_SIGNING_KEY="${SUBJECT_SIGNING_KEY_FILE}" \
  --from-literal=RATE="${RATE:-50}" \
  --from-literal=DURATION="${DURATION:-5m}" \
  --from-literal=WARMUP="${WARMUP:-30s}" \
  --from-literal=REQUEST_TIMEOUT="${REQUEST_TIMEOUT:-30s}" \
  --from-literal=PRE_ALLOCATED_VUS="${PRE_ALLOCATED_VUS:-25}" \
  --from-literal=MAX_VUS="${MAX_VUS:-200}" \
  --from-literal=P95_MS="${P95_MS:-500}" \
  --from-literal=SUCCESS_RATE="${SUCCESS_RATE:-0.99}" \
  --from-literal=INSECURE_SKIP_TLS_VERIFY="${INSECURE_SKIP_TLS_VERIFY:-true}" \
  --dry-run=client -o yaml | kubectl apply -f -

echo "Secrets ready in namespace ${NAMESPACE}: paz-devops-secret, paz-secrets, paz-loadtest"
